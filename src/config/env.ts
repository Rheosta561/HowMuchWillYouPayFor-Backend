import { z } from "zod";
import dotenv from "dotenv";

dotenv.config();

const envSchema = z.object({
  NODE_ENV: z.enum(["development", "test", "production"]).default("development"),
  PORT: z.coerce.number().default(3000),
  MONGODB_URI: z.string().min(1).default("mongodb://127.0.0.1:27017/howmuchwillyoupayfor"),
  JWT_ACCESS_SECRET: z.string().min(16).default("dev-access-secret-change-me-0123456789"),
  JWT_ACCESS_TTL_SECONDS: z.coerce.number().default(900),
  JWT_ISSUER: z.string().min(1).default("howmuchwillyoupayfor"),
  JWT_AUDIENCE: z.string().min(1).default("howmuchwillyoupayfor-api"),
  REFRESH_TOKEN_TTL_DAYS: z.coerce.number().default(30),
  OTP_TTL_MINUTES: z.coerce.number().default(10),
  OTP_MAX_ATTEMPTS: z.coerce.number().default(5),
  OTP_RESEND_COOLDOWN_SECONDS: z.coerce.number().default(60),
  OTP_MAX_REQUESTS_PER_HOUR: z.coerce.number().default(5),
  OTP_HASH_PEPPER: z.string().min(1).default("dev-otp-pepper-change-me"),
  EMAIL_PROVIDER: z.enum(["dev", "resend", "memory"]).default("dev"),
  RESEND_API_KEY: z.string().default(""),
  EMAIL_FROM: z.string().default("HowMuchWillYouPayFor <no-reply@example.com>"),
  AUTH_TOKEN_DELIVERY: z.enum(["body", "cookie", "both"]).default("body"),
  AUTH_REFRESH_COOKIE_NAME: z.string().default("hmwyp_refresh"),
  AUTH_CSRF_COOKIE_NAME: z.string().default("hmwyp_csrf"),
  AUTH_CSRF_HEADER: z.string().default("x-csrf-token"),
  AUTH_REFRESH_COOKIE_SAMESITE: z.enum(["strict", "lax", "none"]).default("lax"),
  REFRESH_REUSE_LEEWAY_SECONDS: z.coerce.number().default(10),
  REFRESH_IP_MAX: z.coerce.number().default(60),
  FRONTEND_ORIGINS: z.string().default("http://localhost:3000"),
  OTP_REQUEST_IP_MAX: z.coerce.number().default(20),
  OTP_VERIFY_IP_MAX: z.coerce.number().default(60),
  RESPONSES_IP_MAX: z.coerce.number().default(60),
  GOOGLE_CLIENT_ID: z.string().default(""),
  GOOGLE_ALLOWED_AUDIENCES: z.string().default(""),
  GOOGLE_AUTH_IP_MAX: z.coerce.number().default(60),
  APP_BASE_URL: z.string().default("http://localhost:3000"),
});
export type Env = z.infer<typeof envSchema>;

export const env: Env = envSchema.parse({
  NODE_ENV: process.env.NODE_ENV,
  PORT: process.env.PORT,
  MONGODB_URI: process.env.MONGODB_URI,
  JWT_ACCESS_SECRET: process.env.JWT_ACCESS_SECRET,
  JWT_ACCESS_TTL_SECONDS: process.env.JWT_ACCESS_TTL_SECONDS,
  JWT_ISSUER: process.env.JWT_ISSUER,
  JWT_AUDIENCE: process.env.JWT_AUDIENCE,
  REFRESH_TOKEN_TTL_DAYS: process.env.REFRESH_TOKEN_TTL_DAYS,
  OTP_TTL_MINUTES: process.env.OTP_TTL_MINUTES,
  OTP_MAX_ATTEMPTS: process.env.OTP_MAX_ATTEMPTS,
  OTP_RESEND_COOLDOWN_SECONDS: process.env.OTP_RESEND_COOLDOWN_SECONDS,
  OTP_MAX_REQUESTS_PER_HOUR: process.env.OTP_MAX_REQUESTS_PER_HOUR,
  OTP_HASH_PEPPER: process.env.OTP_HASH_PEPPER,
  EMAIL_PROVIDER: process.env.EMAIL_PROVIDER,
  RESEND_API_KEY: process.env.RESEND_API_KEY,
  EMAIL_FROM: process.env.EMAIL_FROM,
  AUTH_TOKEN_DELIVERY: process.env.AUTH_TOKEN_DELIVERY,
  AUTH_REFRESH_COOKIE_NAME: process.env.AUTH_REFRESH_COOKIE_NAME,
  AUTH_CSRF_COOKIE_NAME: process.env.AUTH_CSRF_COOKIE_NAME,
  AUTH_CSRF_HEADER: process.env.AUTH_CSRF_HEADER,
  AUTH_REFRESH_COOKIE_SAMESITE: process.env.AUTH_REFRESH_COOKIE_SAMESITE,
  REFRESH_REUSE_LEEWAY_SECONDS: process.env.REFRESH_REUSE_LEEWAY_SECONDS,
  REFRESH_IP_MAX: process.env.REFRESH_IP_MAX,
  FRONTEND_ORIGINS: process.env.FRONTEND_ORIGINS,
  OTP_REQUEST_IP_MAX: process.env.OTP_REQUEST_IP_MAX,
  OTP_VERIFY_IP_MAX: process.env.OTP_VERIFY_IP_MAX,
  RESPONSES_IP_MAX: process.env.RESPONSES_IP_MAX,
  GOOGLE_CLIENT_ID: process.env.GOOGLE_CLIENT_ID,
  GOOGLE_ALLOWED_AUDIENCES: process.env.GOOGLE_ALLOWED_AUDIENCES,
  GOOGLE_AUTH_IP_MAX: process.env.GOOGLE_AUTH_IP_MAX,
  APP_BASE_URL: process.env.APP_BASE_URL,
});
